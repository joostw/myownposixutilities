# diagnostics for lex sources in error; the exit status is non-zero
t() {
    printf '%b' "$1" > bad.l
    $LEX bad.l 2>&1; echo "  status $?"
}
t 'a\tb\n'
t '%%\n(ab\tECHO;\n'
t '%%\nab)\tECHO;\n'
t '%%\n[a-\tECHO;\n'
t '%%\n[z-a]\tECHO;\n'
t '%%\n[[:foo:]]\tECHO;\n'
t '%%\n"abc\tECHO;\n'
t '%%\n{undef}\tECHO;\n'
t 'X {X}\n%%\n{X}\tECHO;\n'
t '%%\na/b/c\tECHO;\n'
t '%%\na/^b\tECHO;\n'
t '%%\na/b$\tECHO;\n'
t '%%\n<NOPE>a\tECHO;\n'
t '%%\na{3,1}\tECHO;\n'
t '%%\n{2}a\tECHO;\n'
t '%%\na{5000}\tECHO;\n'
t '%%\na\t{ ECHO;\n'
t '%%\na\t|\n'
t '%s A A\n%%\n'
t '%foo\n%%\n'
t '%p\n%%\n'
t '1x abc\n%%\n'
t 'X\n%%\n'
t 'X a\nX b\n%%\n'
t '%{\nint x;\n'
t '%%\n\\\n'
t '%%\n[a\tECHO;\n'
t '%%\n[[.ab.]]\tECHO;\n'
t '%%\n\\x100\tECHO;\n'
t 'abc'
